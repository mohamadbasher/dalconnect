/** tiny {param} interpolation, mirrors the mobile t() */
export function fmt(template: string, params: Record<string, string | number>): string {
  return Object.entries(params).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    template,
  );
}
